export function t(key: string, lang: Lang, params?: Record<string, string | number>): string {
  const entry = D[key];
  if (!entry) return key;
  let s = entry[lang === 'tr' ? 0 : 1];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return s;
}

/** Uyari anahtarini i18n anahtarina cevirir (knockRisk → wKnockRisk) */
export function warningKey(key: string): string {
  return 'w' + key.charAt(0).toUpperCase() + key.slice(1);
}
